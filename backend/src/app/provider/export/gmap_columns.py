def gmap_identity(place_id: str | None, fid: str | None) -> str:
    """优先以 Place Id 判重，缺失时以 Fid 判重；空串表示无有效身份。"""
    return f"place:{place_id}" if place_id else f"fid:{fid}" if fid else ""


